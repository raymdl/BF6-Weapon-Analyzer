def sha(b): return hashlib.sha256(b).hexdigest()
def norm(text): return text.replace('\r\n', '\n')
def canon_sha(raw): return sha(raw.replace(b'\r\n', b'\n'))  # the form git stores; independent of checkout line endings
def line_end_hashes(raw):
    lf = raw.replace(b'\r\n', b'\n')
    return {sha(raw), sha(lf), sha(lf.replace(b'\n', b'\r\n'))}
def jdump(obj): return json.dumps(obj, indent=2, ensure_ascii=False) + '\n'
def lead_sort(i): m = re.fullmatch(r'L(\d+)([A-Z]?)', i); return (int(m[1]), m[2]) if m else (10**9, i)
def name_date(name):
    found = DATE.findall(name)
    return found[-1] if found else None
def is_date(s):
    try: datetime.date.fromisoformat(s); return bool(DATE.fullmatch(s))
    except (TypeError, ValueError): return False


class Receipt:
    def __init__(self, name, path, raw):
        self.name, self.path, self.raw, self.err, self.obj = name, path, raw, None, None
        try: self.obj = json.loads(raw.decode('utf-8-sig'))
        except (ValueError, UnicodeDecodeError) as e: self.err = str(e)


class Ctx:
    def __init__(self, a):
        self.site = Path(a.site_root or REPO).resolve()
        self.research = Path(a.research_root or REPO).resolve()
        self.dm = Path(a.datamining_root).resolve() if a.datamining_root else self.research.parent / 'BF6 Datamining'
        self.prov_dirs = [self.research / 'reference-data/provenance']
        if self.site != self.research: self.prov_dirs.append(self.site / 'reference-data/provenance')
        self.frosty = self.research / 'reference-data/frosty'
        self._receipts = self._resolver = None
        self.problems = []  # (severity, category, message)

    def err(self, cat, msg): self.problems.append(('error', cat, msg))
    def warn(self, cat, msg): self.problems.append(('warning', cat, msg))
    def text(self, rel, root=None):
        p = (root or self.research) / rel
        return norm(p.read_text(encoding='utf-8-sig')) if p.exists() else ''

    @property
    def receipts(self):
        if self._receipts is None:
            self._receipts = {}
            for d in self.prov_dirs:
                for p in sorted(d.glob('*.json')):
                    if p.name == SIDECAR: continue
                    if p.name in self._receipts: self.err('receipt', f'{p.name}: exists in more than one provenance folder')
                    self._receipts[p.name] = Receipt(p.name, p, p.read_bytes())
        return self._receipts

    def sidecar(self):
        p = self.prov_dirs[0] / SIDECAR
        if not p.exists(): return {}
        try: data = json.loads(p.read_text(encoding='utf-8-sig'))
        except ValueError as e: self.err('sidecar', f'{SIDECAR} does not parse: {e}'); return {}
        if not isinstance(data, dict): self.err('sidecar', f'{SIDECAR} must be an object keyed by receipt file name'); return {}
        return data

    def pointer_resolver(self):
        """resolve_pointer from frosty-worker.py (single-match behaviour untouched), pointed at --site-root with a file cache."""
        if self._resolver is None:
            fn = runpy.run_path(str(self.research / 'scripts/frosty-worker.py'))['resolve_pointer']
            g, cache, load = fn.__globals__, {}, fn.__globals__['load_json']
            g['ROOT'] = self.site
            def cached(p):
                if str(p) not in cache: cache[str(p)] = load(p)
                return cache[str(p)]
            g['load_json'] = cached
            self._resolver = fn
        return self._resolver

    def resolve_all(self, pointer):
        """Values for a pointer; a `[key=value]*` step expands to every matching list element."""
        fn = self.pointer_resolver()
        file, _, path = pointer.partition(':')
        parts = [p for p in path.split('/') if p]
        for i, part in enumerate(parts):
            m = re.fullmatch(r'\[(\w+)=(.+)\]\*', part)
            if not m: continue
            node = fn(file + ':/' + '/'.join(parts[:i]))
            out = []
            for idx, x in enumerate(node if isinstance(node, list) else []):
                if isinstance(x, dict) and str(x.get(m[1])) == m[2]:
                    out += self.resolve_all(file + ':/' + '/'.join(parts[:i] + [str(idx)] + parts[i + 1:]))
            if not out: raise KeyError(f'{pointer}: no element with {m[1]}={m[2]}')
            return out
        return [fn(pointer)]


# ---------------------------------------------------------------- record validation

def validate_record(rec, name_dt=None):
    """Structural errors for one record object (list of strings)."""
    if not isinstance(rec, dict): return ['record is not an object']
    e = [f'unknown key {k}' for k in sorted(set(rec) - RECORD_KEYS)]
    if rec.get('v') != 1: e.append('v must be 1')
    if rec.get('kind') not in KINDS: e.append(f'kind must be one of {KINDS}')
    d = rec.get('date')
    if not is_date(d): e.append('date must be YYYY-MM-DD')
    elif name_dt and d != name_dt: e.append(f'date {d} differs from the file-name date {name_dt}')
    if rec.get('build') not in BUILDS: e.append(f'build must be one of {list(BUILDS)}')
    if 'binding' in rec and rec['binding'] not in BINDINGS: e.append(f'binding must be one of {BINDINGS}')
    leads = rec.get('leads', [])
    if not isinstance(leads, list): e.append('leads must be a list'); leads = []
    if rec.get('kind') in ('lead', 'decision') and not leads: e.append(f'kind {rec.get("kind")} needs at least one lead')
    seen = set()
    for i, l in enumerate(leads):
        w = f'leads[{i}]'
        if not isinstance(l, dict): e.append(f'{w} is not an object'); continue
        e += [f'{w}: unknown key {k}' for k in sorted(set(l) - LEAD_KEYS)]
        if not (isinstance(l.get('id'), str) and LEAD_ID.fullmatch(l['id'])): e.append(f'{w}: id must look like L17 or L68C')
        elif l['id'] in seen: e.append(f'{w}: duplicate id {l["id"]}')
        else: seen.add(l['id'])
        if l.get('status') not in STATUSES: e.append(f'{w}: status must be one of {STATUSES}')
        for k in ('title', 'summary', 'reopenWhen'):
            if not (isinstance(l.get(k), str) and l[k].strip()): e.append(f'{w}: {k} must be a non-empty string')
        if 'statusNote' in l and not isinstance(l['statusNote'], str): e.append(f'{w}: statusNote must be a string')
        if l.get('status') == 'exhausted' and not (isinstance(l.get('searched'), list) and l['searched'] and all(isinstance(x, str) and x for x in l['searched'])):
            e.append(f'{w}: exhausted needs a non-empty searched list (fields, value searches, catalog scope, callers)')
    assets = rec.get('assets', [])
    if not isinstance(assets, list): e.append('assets must be a list'); assets = []
    for i, a in enumerate(assets):
        w = f'assets[{i}]'
        if not isinstance(a, dict): e.append(f'{w} is not an object'); continue
        e += [f'{w}: unknown key {k}' for k in sorted(set(a) - ASSET_KEYS)]
        if not (isinstance(a.get('path'), str) and a['path'] and not a['path'].lower().endswith(('.ebx', '.xml'))): e.append(f'{w}: path must be an internal Frosty path without .ebx/.xml')
        if a.get('format') not in FORMATS: e.append(f'{w}: format must be one of {FORMATS}')
        if not (isinstance(a.get('sha256'), str) and HEX64.fullmatch(a['sha256'])): e.append(f'{w}: sha256 must be 64 lowercase hex')
        if a.get('result') not in RESULTS: e.append(f'{w}: result must be one of {RESULTS}')
        for k in ('question', 'conclusion'):
            if not (isinstance(a.get(k), str) and a[k].strip()): e.append(f'{w}: {k} must be a non-empty string')
    site = rec.get('site', [])
    if not isinstance(site, list): e.append('site must be a list'); site = []
    for i, s in enumerate(site):
        w = f'site[{i}]'
        if not isinstance(s, dict): e.append(f'{w} is not an object'); continue
        e += [f'{w}: unknown key {k}' for k in sorted(set(s) - SITE_KEYS)]
        if not (isinstance(s.get('pointer'), str) and re.match(r'[^:]+\.(json|js):', s['pointer'])): e.append(f'{w}: pointer must look like data/file.json:/path')
        if s.get('relation') not in RELATIONS: e.append(f'{w}: relation must be one of {RELATIONS}')
    if 'siteRows' in rec:
        sr = rec['siteRows']
        if not (isinstance(sr, dict) and isinstance(sr.get('rows'), str) and all(isinstance(sr.get(k), int) for k in ('file', 'pointer'))):
            e.append('siteRows must be {rows: pointer string, file: int, pointer: int, value: int}')
    if 'refs' in rec and not (isinstance(rec['refs'], list) and set(rec['refs']) <= set(REF_FILES)): e.append(f'refs must be a list drawn from {list(REF_FILES)}')
    if 'supersedes' in rec and not (isinstance(rec['supersedes'], list) and all(isinstance(x, str) for x in rec['supersedes'])): e.append('supersedes must be a list of receipt file names')
    if 'run' in rec and not isinstance(rec['run'], dict): e.append('run must be an object')
    return e


def load_records(ctx):
    """[(name, record, where)] for every receipt; structural problems go to ctx.problems."""
    side, out = ctx.sidecar(), []
    for name, r in ctx.receipts.items():
        if r.err: ctx.err('receipt', f'{name}: does not parse ({r.err})'); continue
        emb = r.obj.get('record') if isinstance(r.obj, dict) else None
        leg = side.get(name)
        if emb is not None and leg is not None: ctx.err('record', f'{name}: has both an embedded record and a {SIDECAR} entry'); continue
        if emb is None and leg is None: ctx.err('record', f'{name}: no record (embed one, or list it in {SIDECAR})'); continue
        if leg is not None:
            if not (isinstance(leg, dict) and isinstance(leg.get('record'), dict) and isinstance(leg.get('sha256'), str)):
                ctx.err('sidecar', f'{name}: entry must be {{"sha256", "record"}}'); continue
            if leg['sha256'] != canon_sha(r.raw): ctx.err('sidecar', f'{name}: file changed since its record was written (committed receipts are superseded, not edited)')
        rec, where = (emb, 'embedded') if leg is None else (leg['record'], 'sidecar')
        errs = validate_record(rec, name_date(name))
        for m in errs: ctx.err('record', f'{name}: {m}')
        if not errs: out.append((name, rec, where))
    for name in sorted(set(side) - set(ctx.receipts)): ctx.err('sidecar', f'{name}: listed in {SIDECAR} but no such receipt')
    return out


# ---------------------------------------------------------------- queue and doc parsing

def section(text, heading):
    """Body of the `heading` section (up to the next heading of the same or a higher level)."""
    m = re.search(r'^(#+) ' + re.escape(heading) + r'\s*$', text, re.M)
    if not m: return ''
    level = len(m[1])
    rest = text[m.end():]
    end = re.search(r'^#{1,%d} ' % level, rest, re.M)
    return rest[:end.start()] if end else rest

def table_rows(body):
    return [[c.strip() for c in l.strip().strip('|').split(' | ')] for l in body.split('\n') if l.startswith('| L')]

def active_leads(ctx):
    return {c[0]: c for c in table_rows(section(ctx.text(QUEUE), 'Active source leads')) if LEAD_ID.fullmatch(c[0])}

def mentions(text, lead_id):
    """The lead id appears in the text, alone or inside a range such as L100-L104."""
    if re.search(r'(?<![A-Za-z0-9])' + re.escape(lead_id) + r'(?![0-9A-Za-z])', text): return True
    n = int(re.sub(r'\D', '', lead_id))
    return any(int(a) <= n <= int(b) for a, b in re.findall(r'L(\d+)[A-Z]?\s*[–—-]\s*L?(\d+)', text))


# ---------------------------------------------------------------- generated files

def index_leads(recs):
    """lead id -> newest entry across records (date, then file name), plus every receipt naming it."""
    per = collections.defaultdict(list)
    for name, rec, _ in recs:
        for l in rec.get('leads', []): per[l['id']].append((rec['date'], name, l, rec))
    out = {}
    for lid in sorted(per, key=lead_sort):
        rows = sorted(per[lid], key=lambda x: (x[0], x[1]))
        date, name, l, rec = rows[-1]
        entry = {'id': lid, 'title': l['title'], 'status': l['status']}
        if l.get('statusNote'): entry['statusNote'] = l['statusNote']
        entry.update({'date': date, 'receipts': [r[1] for r in rows], 'summary': l['summary'], 'reopenWhen': l['reopenWhen'],
                      'refs': sorted({x for r in rows for x in r[3].get('refs', [])})})
        out[lid] = entry
    return out

def closed_table(index, active):
    rows = ['| # | Lead | Established | Next source step |', '|---|---|---|---|']
    for lid, e in index.items():
        if lid in active: continue
        title = e['title'] + (f' - {e["statusNote"]}' if e.get('statusNote') else '')
        rows.append(f'| {lid} | **{title}** | {e["summary"]} | {e["reopenWhen"]} |')
    return '\n'.join(rows)

def render_archive(text, table):
    block = f'{GEN_START}\n<!-- {NOTE} Source: reference-data/frosty/lead-index.json -->\n\n{table}\n{GEN_END}'
    if GEN_START in text and GEN_END in text:
        a, b = text.index(GEN_START), text.index(GEN_END) + len(GEN_END)
        return text[:a] + block + text[b:]
    m = re.search(r'^## Closed leads[ \t]*\n', text, re.M)
    if not m: return None
    nxt = re.search(r'^## ', text[m.end():], re.M)
    end = m.end() + nxt.start() if nxt else len(text)
    return text[:m.end()] + '\n' + block + '\n\n' + text[end:]

def build_findings(ctx, recs):
    base_path = ctx.frosty / 'asset-findings-base.json'
    base = json.loads(base_path.read_text(encoding='utf-8-sig'))
    out = {'schemaVersion': base['schemaVersion'], 'generated': NOTE + ' Base: asset-findings-base.json (frozen); added: record.assets of later receipts.'}
    out.update({k: v for k, v in base.items() if k != 'schemaVersion'})
    out['evidence'], out['assets'] = dict(base['evidence']), {k: {'contents': v['contents'], 'findings': list(v['findings'])} for k, v in base['assets'].items()}
    lower = {k.lower(): k for k in out['assets']}
    stems = {}
    for name, rec, where in sorted(recs, key=lambda x: (x[1]['date'], x[0])):
        if not rec.get('assets'): continue
        stem = name[:-5]; stems[name] = stem
        out['evidence'][stem] = {'path': 'reference-data/provenance/' + name, 'reportSha256': canon_sha(ctx.receipts[name].raw)}
        b = BUILDS[rec['build']]
        reopen = ' '.join(dict.fromkeys(l['reopenWhen'] for l in rec.get('leads', [])))
        for a in rec['assets']:
            key = lower.setdefault(a['path'].lower(), a['path'])
            entry = out['assets'].setdefault(key, {'contents': a.get('contents') or f'Traced by {stem}.', 'findings': []})
            entry['findings'].append({
                'question': a['question'], 'result': a['result'], 'conclusion': a['conclusion'],
                'buildInspected': {'label': b['label'], 'exactBuildVerified': b['head'] is not None,
                                   'basis': f'record.build {rec["build"]}' + (f'; Head {b["head"]}' if b['head'] else '')},
                'evidence': [{'source': stem, 'pointer': '/record' if where == 'embedded' else None}],
                'assetHashesAtInspection': [{'format': a['format'], 'sha256': a['sha256']}],
                'inspectionDate': rec['date'], 'revisitWhen': REVISIT + ([reopen] if reopen else [])})
    ids_by_receipt = {v['path'].rsplit('/', 1)[-1]: k for k, v in out['evidence'].items()}
    for name, rec, _ in recs:  # explicit history links: earlier findings name the record that supersedes them
        if name not in stems: continue
        for old in rec.get('supersedes', []):
            old_id = ids_by_receipt.get(old)
            for asset in out['assets'].values():
                for f in asset['findings']:
                    if old_id and any(e['source'] == old_id for e in f['evidence']):
                        f['supersededBy'] = sorted(set(f.get('supersededBy', []) + [stems[name]]))
    return out

def build_site_evidence(recs):
    ptrs = collections.defaultdict(list)
    for name, rec, _ in recs:
        for s in rec.get('site', []):
            row = {'receipt': name, 'date': rec['date'], 'relation': s['relation']}
            if 'value' in s: row['value'] = s['value']
            ptrs[s['pointer']].append(row)
        sr = rec.get('siteRows')
        if sr: ptrs[f'{name}:{sr["rows"]}'] = [{'receipt': name, 'date': rec['date'], 'relation': 'context', 'siteRows': sr}]
    return {'v': 1, 'generated': NOTE, 'pointers': {p: sorted(ptrs[p], key=lambda r: (r['date'], r['receipt'])) for p in sorted(ptrs)}}

def generate(ctx, recs):
    """relative path (from --research-root) -> generated text."""
    index = index_leads(recs)
    out = {'reference-data/frosty/asset-findings.json': jdump(build_findings(ctx, recs)),
           'reference-data/frosty/lead-index.json': jdump({'v': 1, 'generated': NOTE, 'leads': index}),
           'reference-data/frosty/site-evidence.json': jdump(build_site_evidence(recs))}
    arch = render_archive(ctx.text(ARCHIVE), closed_table(index, active_leads(ctx)))
    if arch is not None: out[ARCHIVE] = arch
    return out


