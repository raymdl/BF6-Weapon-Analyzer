"""Durable Frosty research records (see docs/frosty/TOOLS.md "Frosty records").

schema                          print the record header (v1) that every receipt carries
check [--external] [--all]      validate receipts, records and generated files; exit 1 on errors only
check-receipt FILE              validate one draft receipt's `record` (read-only)
status                          short summary for orchestrators at run start
build                           regenerate asset-findings.json, lead-index.json, site-evidence.json
                                and the Closed leads table in docs/archive/FROSTY_QUEUE_CLOSED.md
ledger-drift [--out F]          data/sim files and data leaves that differ from the site-input ledger
new --kind decision --lead L67  write a skeleton decision record under reference-data/provenance/

Roots: --site-root (data/, sim/, ui/; pointers resolve here), --research-root (receipts, docs, queue),
--datamining-root (external evidence; default <research-root>/../BF6 Datamining). All default to the repo.
Receipts committed before the cutover carry their `record` in reference-data/provenance/records-legacy.json,
keyed by file name with the receipt's sha256 (CRLF read as LF, the form git stores); a committed receipt is never edited, only superseded.
"""
