SITE_FILES = ('index.html', 'ship-surface.json')
def site_layer_files(ctx):
    files = [ctx.site / f for f in SITE_FILES] + [p for d in ('data', 'sim', 'ui', 'schemas', '.github') for p in sorted((ctx.site / d).rglob('*')) if p.is_file()]
    files += [p for p in sorted((ctx.site / 'scripts').glob('*')) if p.suffix in ('.mjs', '.js')]
    return [p for p in files if p.is_file() and p.suffix in ('.json', '.js', '.mjs', '.html', '.yml', '.yaml')]

def derive_binding(ctx):
    """receipt name -> 'site' when a site-layer file pins its sha256 or names it by path, else 'research'."""
    hashes = {}
    for n, r in ctx.receipts.items():
        for h in line_end_hashes(r.raw): hashes[h] = n
    site = set()
    for p in site_layer_files(ctx):
        text = p.read_text(encoding='utf-8', errors='replace')
        site.update(hashes[h] for h in set(HEX64.findall(text)) if h in hashes)
        site.update(n for n in set(re.findall(r'[A-Za-z0-9._-]+\.json', text)) if n in ctx.receipts)
    return {n: ('site' if n in site else 'research') for n in ctx.receipts}

def flatten(o, p=''):
    if isinstance(o, dict) and o:
        for k, v in o.items(): yield from flatten(v, p + '/' + str(k).replace('~', '~0').replace('/', '~1'))
    elif isinstance(o, list) and o:
        for i, v in enumerate(o): yield from flatten(v, p + f'/{i}')
    else: yield p, o

def latest(ctx, pattern):
    return sorted(ctx.prov_dirs[0].glob(pattern), key=lambda p: (re.findall(r'v(\d+)', p.name) or ['0'], p.name))[-1:]

def inventories(ctx):
    """Site-input inventory receipts, newest first: [(path, parsed)]."""
    paths = sorted(ctx.prov_dirs[0].glob('frosty-site-input-inventory-v*.json'), key=lambda p: (int((re.findall(r'-v(\d+)-', p.name) or ['0'])[0]), p.name), reverse=True)
    return [(p, json.loads(p.read_text(encoding='utf-8-sig'))) for p in paths]

def ledger_files(ctx):
    """{site file: (pinned sha256, inventory path, parsed)} from the newest inventory that lists the file as reviewed.
    An inventory marks files it only enumerated (not reviewed) with "reviewed": false; those keep their older baseline."""
    seen = {}
    for p, d in inventories(ctx):
        for f in d.get('files', []):
            if f['path'] not in seen and f.get('reviewed', True): seen[f['path']] = (f['sha256'], p, d)
    return seen

def file_drift(ctx):
    files = ledger_files(ctx)
    out = []
    for rel, (pinned, _, _) in sorted(files.items()):
        p = ctx.site / rel
        if not p.exists(): out.append((rel, 'missing')); continue
        if pinned not in line_end_hashes(p.read_bytes()): out.append((rel, 'changed'))
    return list(files), out

def rebase_external(ctx, path):
    parts = re.split(r'[\\/]', path)
    return ctx.dm.joinpath(*parts[parts.index('BF6 Datamining') + 1:]) if 'BF6 Datamining' in parts else Path(path)

def reviewed_jsonl(ctx):
    rev = latest(ctx, 'frosty-site-input-review-final-v*.json')
    if not rev: return None
    d = json.loads(rev[0].read_text(encoding='utf-8-sig'))
    for p in (d.get('details') or {}).values() if isinstance(d.get('details'), dict) else []:
        if isinstance(p, str) and p.endswith('site-input-reviewed.jsonl'): return rebase_external(ctx, p)
    return None


