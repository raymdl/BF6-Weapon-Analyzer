def run_checks(ctx, external=False):
    recs = load_records(ctx)
    binding = derive_binding(ctx)
    ids = {l['id'] for _, rec, _ in recs for l in rec.get('leads', [])}
    # generated outputs
    if not any(c in ('receipt', 'record', 'sidecar') for _, c, _ in ctx.problems):
        if not (ctx.frosty / 'asset-findings-base.json').exists(): ctx.err('generated', 'reference-data/frosty/asset-findings-base.json is missing')
        else:
            gen = generate(ctx, recs)
            if ARCHIVE not in gen: ctx.err('generated', f'{ARCHIVE}: no "## Closed leads" heading or {GEN_START} markers')
            for rel, text in gen.items():
                p = ctx.research / rel
                if not p.exists() or norm(p.read_text(encoding='utf-8-sig')) != text: ctx.err('generated', f'{rel}: out of date; run build')
    # consistency warnings
    for name, rec, where in recs:
        if 'binding' in rec and rec['binding'] != binding[name]: ctx.warn('binding', f'{name}: record says {rec["binding"]}, the pin/reference scan says {binding[name]}')
        if 'binding' not in rec: ctx.warn('binding', f'{name}: no binding stored (scan says {binding[name]})')
        for old in rec.get('supersedes', []):
            if old not in ctx.receipts: ctx.warn('supersedes', f'{name}: supersedes unknown receipt {old}')
        for ref in rec.get('refs', []):
            doc = ctx.text(REF_FILES[ref]) + (ctx.text(ARCHIVE) if ref == 'queue-proposals' else '')  # applied proposals live in the archive
            if rec.get('leads') and not any(mentions(doc, l['id']) for l in rec['leads']):
                ctx.warn('refs', f'{name}: none of {[l["id"] for l in rec["leads"]]} found in {REF_FILES[ref]}')
        for s in rec.get('site', []):
            try: vals = ctx.resolve_all(s['pointer'])
            except (KeyError, IndexError, ValueError, OSError) as e:
                if s['relation'] != 'changed': ctx.warn('stale-pointer', f'{name}: {e}')
                continue
            if 'value' in s and all(v != s['value'] for v in vals) and s['relation'] != 'changed':
                ctx.warn('value-changed', f'{name}: {s["pointer"]} was {s["value"]!r}, now {vals[0]!r}' if len(vals) == 1 else f'{name}: {s["pointer"]} no longer equals {s["value"]!r}')
        if rec.get('siteRows'): check_site_rows(ctx, name, rec['siteRows'])
    recmap = {n: r for n, r, _ in recs}
    per = collections.defaultdict(list)
    for name, rec, _ in recs:
        for l in rec.get('leads', []): per[l['id']].append((rec['date'], name, l))
    for lid, rows in sorted(per.items(), key=lambda x: lead_sort(x[0])):
        rows.sort(key=lambda x: (x[0], x[1]))
        if len({r[2]['title'] for r in rows}) > 1: ctx.warn('lead-title', f'{lid}: more than one title across {[r[1] for r in rows]}')
        chain = [r[2]['status'] for r in rows]
        if len(set(chain)) > 1 and not any(recmap[r[1]].get('supersedes') for r in rows[1:]):
            ctx.warn('lead-status', f'{lid}: status changes {" -> ".join(chain)} without a superseding record')
    active = active_leads(ctx)
    latest_status = {lid: rows[-1][2]['status'] for lid, rows in per.items()}
    for lid in active:
        if latest_status.get(lid) not in (None, 'needs-capture'): ctx.warn('queue', f'{lid}: in the Active table but its record says {latest_status[lid]}')
    for name in ctx.receipts:
        for tok in set(re.findall(r'(?<![A-Za-z])L(\d+)', name)):
            if f'L{tok}' not in ids and not any(i.startswith(f'L{tok}') for i in ids) and name not in ('records-legacy.json',):
                ctx.warn('lead-record', f'{name}: names L{tok} but no record carries that lead')
    props = section(ctx.text(QUEUE), 'Proposed Analyzer changes') + section(ctx.text(ARCHIVE), 'Applied proposals')
    capture = ctx.text(REF_FILES['capture-plan'])
    for lid, st in sorted(latest_status.items(), key=lambda x: lead_sort(x[0])):
        if st == 'proposal' and not mentions(props, lid): ctx.warn('proposal', f'{lid}: proposal lead is not in the queue proposal table or the applied proposals')
        if st == 'needs-capture' and not mentions(capture, lid): ctx.warn('capture', f'{lid}: needs-capture lead is not in the capture plan')
    files, drift = file_drift(ctx)
    if drift: ctx.warn('ledger-stale', f'{len(drift)} of {len(files)} ledger files differ from the pinned hashes ({", ".join(r for r, _ in drift)}); run ledger-drift')
    if external: external_checks(ctx, recs)
    return recs, drift

def json_pointer(obj, ptr):
    for part in [p for p in ptr.split('/') if p]:
        obj = obj[int(part)] if isinstance(obj, list) else obj[part]
    return obj

def check_site_rows(ctx, name, sr):
    """Audit receipts list site values as rows [file, pointer, value, ...]; warn (once per receipt) about rows that no longer resolve or differ."""
    try: rows = json_pointer(ctx.receipts[name].obj, sr['rows'])
    except (KeyError, IndexError, ValueError, TypeError): ctx.warn('stale-pointer', f'{name}: siteRows.rows {sr["rows"]} not found in the receipt'); return
    gone, moved, first = 0, 0, None
    for row in rows:
        try: vals = ctx.resolve_all(f'{row[sr["file"]]}:{row[sr["pointer"]]}')
        except (KeyError, IndexError, ValueError, OSError): gone += 1; first = first or f'{row[sr["file"]]}:{row[sr["pointer"]]}'; continue
        if 'value' in sr and vals[0] != row[sr['value']]: moved += 1
    if gone: ctx.warn('stale-pointer', f'{name}: {gone} of {len(rows)} siteRows pointers no longer resolve (first: {first})')
    if moved: ctx.warn('value-changed', f'{name}: {moved} of {len(rows)} siteRows values differ from the current site')

def external_checks(ctx, recs):
    if not ctx.dm.exists(): ctx.warn('external', f'{ctx.dm} not found; skipped'); return
    raw_root = ctx.dm / 'builds/1.4.3.0/capture/collection/raw'
    for name, rec, _ in recs:
        for a in rec.get('assets', []):
            f = raw_root / (a['path'] + '.ebx')
            if a['format'] == 'raw-ebx' and f.exists() and sha(f.read_bytes()) != a['sha256']:
                ctx.warn('asset-hash', f'{name}: {a["path"]} raw sha256 differs from the current capture')
    inv = latest(ctx, 'frosty-site-input-inventory-v*.json')
    for x in (json.loads(inv[0].read_text(encoding='utf-8-sig')).get('artifacts', []) if inv else []):
        f = rebase_external(ctx, x['path'])
        if not f.exists(): ctx.warn('external', f'ledger artifact not found: {f}')
        elif sha(f.read_bytes()) != x['sha256']: ctx.warn('external', f'ledger artifact hash differs: {f.name}')
    rj = reviewed_jsonl(ctx)
    if rj is None or not rj.exists(): ctx.warn('external', 'site-input-reviewed.jsonl not found; ledger-row checks skipped')

def print_problems(ctx, show_all=False, limit=8):
    by = collections.defaultdict(list)
    for sev, cat, msg in ctx.problems: by[(sev, cat)].append(msg)
    for (sev, cat), msgs in sorted(by.items(), key=lambda x: (x[0][0] != 'error', x[0][1])):
        for m in (msgs if show_all else msgs[:limit]): print(f'{sev.upper()} [{cat}] {m}')
        if not show_all and len(msgs) > limit: print(f'  ... {len(msgs) - limit} more [{cat}] {sev}s (use --all)')
    return sum(1 for p in ctx.problems if p[0] == 'error'), sum(1 for p in ctx.problems if p[0] == 'warning')

def cmd_check(a, ctx):
    recs, drift = run_checks(ctx, a.external)
    e, w = print_problems(ctx, a.all)
    print(f'{len(ctx.receipts)} receipts, {len(recs)} valid records; {e} errors, {w} warnings')
    sys.exit(1 if e else 0)

def cmd_check_receipt(a, ctx):
    p = Path(a.file)
    try: obj = json.loads(p.read_text(encoding='utf-8-sig'))
    except (OSError, ValueError) as e: raise SystemExit(f'{p}: {e}')
    if not isinstance(obj, dict) or 'record' not in obj: raise SystemExit(f'{p}: no top-level "record" object; run `frosty-records.py schema`')
    errs = validate_record(obj['record'], name_date(p.name))
    if not errs:
        r = obj['record']
        for s in r.get('site', []):
            try: ctx.resolve_all(s['pointer'])
            except (KeyError, IndexError, ValueError, OSError) as e: print(f'WARNING site pointer: {e}')
    for m in errs: print(f'ERROR {m}')
    print(f'{p.name}: {"record ok" if not errs else str(len(errs)) + " errors"}')
    sys.exit(1 if errs else 0)

def cmd_build(a, ctx):
    recs = load_records(ctx)
    bad = [m for s, c, m in ctx.problems if s == 'error' and c in ('receipt', 'record', 'sidecar')]
    if bad:
        for m in bad[:10]: print('ERROR', m)
        raise SystemExit(f'{len(bad)} receipt/record errors; fix them before build')
    gen = generate(ctx, recs)
    if ARCHIVE not in gen: raise SystemExit(f'{ARCHIVE}: no "## Closed leads" heading')
    changed = []
    for rel, text in sorted(gen.items()):
        p = ctx.research / rel
        if p.exists() and norm(p.read_text(encoding='utf-8-sig')) == text: continue
        p.write_text(text, encoding='utf-8', newline='\n'); changed.append(rel)
    print('changed: ' + (', '.join(changed) if changed else 'nothing'))

def cmd_status(a, ctx):
    recs, drift = run_checks(ctx)
    e = sum(1 for p in ctx.problems if p[0] == 'error'); w = sum(1 for p in ctx.problems if p[0] == 'warning')
    index = index_leads(recs)
    active = active_leads(ctx)
    lines = [f'Frosty records: {len(ctx.receipts)} receipts, {len(recs)} records, {len(index)} leads; check {e} errors, {w} warnings']
    if e:
        lines += [f'  ERROR [{c}] {m}'[:150] for s, c, m in ctx.problems if s == 'error'][:5]
    lines.append(f'Live leads (queue Active table, {len(active)}):')
    for lid, c in active.items():
        st = index[lid]['status'] if lid in index else 'no record'
        title = re.sub(r'\*\*|\s+-\s+.*', '', c[1])[:70]
        lines.append(f'  {lid} [{st}] {title}')
    q = ctx.text(QUEUE)
    aw = next((section(q, h) for h in re.findall(r'^### (Awaiting operator[^\n]*)$', q, re.M)), '')
    items = re.findall(r'^- (.*(?:\n  .*)*)', aw, re.M)
    lines.append(f'Awaiting the operator ({len(items)}):')
    for it in items: lines.append('  - ' + re.sub(r'\s+', ' ', re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', it))[:135])
    props = section(q, 'Proposed Analyzer changes')
    pending = [re.sub(r'\*\*|\s+\(L\d.*', '', r[0]).strip()[:60] for r in (l.strip().strip('|').split(' | ') for l in props.split('\n') if l.startswith('| **'))]
    lines.append(f'Proposal rows flagged for the operator ({len(pending)}):')
    for p in pending[:8]: lines.append('  - ' + p)
    if len(pending) > 8: lines.append(f'  ... {len(pending) - 8} more in the queue')
    counts = collections.Counter(e_['status'] for e_ in index.values())
    lines.append('Lead statuses: ' + ', '.join(f'{k} {v}' for k, v in counts.most_common()))
    lines.append('Latest recorded leads:')
    for e_ in sorted(index.values(), key=lambda x: (x['date'], lead_sort(x['id'])), reverse=True)[:6]:
        lines.append(f'  {e_["id"]} {e_["date"]} [{e_["status"]}] {e_["title"][:60]}')
    files, dr = file_drift(ctx)
    lines.append(f'Site-input ledger: {len(dr)} of {len(files)} pinned files changed since the 23 Sep inventory (' + '; '.join(f'{d} {sum(1 for r, _ in dr if r.startswith(d + "/"))}' for d in ('data', 'sim')) + '); ledger-drift lists the leaves')
    stale = sum(1 for s, c, m in ctx.problems if c == 'stale-pointer')
    lines.append(f'Stale site pointers in records: {stale}. Close-out: receipt with a record, topic page, remove the queue row, then build && check.')
    print('\n'.join(lines[:59]))

def artifact_path(ctx, d, suffix):
    return next((rebase_external(ctx, x['path']) for x in d.get('artifacts', []) if x['path'].endswith(suffix)), None)

def review_statuses(ctx):
    """(site file, pointer) -> reviewStatus: the reviewed ledger rows, overlaid by each inventory's delta ledger (oldest first)."""
    status = {}
    rj = reviewed_jsonl(ctx)
    if rj and rj.exists():
        with open(rj, encoding='utf-8') as f:
            for l in f:
                r = json.loads(l); status[(r['siteFile'], r['pointer'])] = r.get('reviewStatus')
    else: print(f'{rj}: reviewed ledger not found; review status omitted')
    for p, d in reversed(inventories(ctx)):
        art = (d.get('delta') or {}).get('artifact')
        f = rebase_external(ctx, art['path']) if art else None
        if f and f.exists():
            with open(f, encoding='utf-8') as fh:
                for l in fh:
                    r = json.loads(l)
                    if r['change'] == 'removed': status.pop((r['siteFile'], r['pointer']), None)
                    else: status[(r['siteFile'], r['pointer'])] = r.get('reviewStatus')
    return status

def code_lines(text):
    """(line number, code) for the nonblank, non-comment lines, as frosty-site-input-inventory.py indexes sim code."""
    out, block = [], False
    for n, original in enumerate(text.splitlines(), 1):
        line = original.strip()
        if block:
            if '*/' in line: block, line = False, line.split('*/', 1)[1].strip()
            else: continue
        if line.startswith('/*'):
            if '*/' in line: line = line.split('*/', 1)[1].strip()
            else: block = True; continue
        if line and not line.startswith('//'): out.append((n, original))
    return out

def sim_diff(ctx, rel, baseline_lines):
    old = [code for f, n, code in baseline_lines if f == rel]
    cur = code_lines((ctx.site / rel).read_text(encoding='utf-8-sig'))
    ranges = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, old, [c for _, c in cur], autojunk=False).get_opcodes():
        if tag != 'equal': ranges.append((cur[j1][0] if j2 > j1 else (cur[j1 - 1][0] if j1 else 1), cur[j2 - 1][0] if j2 > j1 else None, i2 - i1, j2 - j1))
    return ranges

def cmd_ledger_drift(a, ctx):
    files, drift = file_drift(ctx)
    seen = ledger_files(ctx)
    print(f'{len(drift)} of {len(files)} ledger files differ from the pinned hashes:')
    for rel, why in drift: print(f'  {rel}: {why} (baseline {seen[rel][1].name})')
    status = review_statuses(ctx)
    out = {'changed': [], 'removed': [], 'new': []}
    by_inv = collections.defaultdict(list)
    for rel in files:
        if rel.startswith('data/'): by_inv[seen[rel][1]].append(rel)
    for inv_path, rels in by_inv.items():
        leaves = artifact_path(ctx, seen[rels[0]][2], 'site-input-leaves.jsonl')
        if leaves is None or not leaves.exists(): print(f'external leaf list not found ({leaves}); skipping leaves for {inv_path.name}'); continue
        old = collections.defaultdict(dict)
        with open(leaves, encoding='utf-8') as f:
            for l in f:
                r = json.loads(l)
                if r['siteFile'] in rels: old[r['siteFile']][r['pointer']] = r['siteValue']
        for rel in sorted(old):
            p = ctx.site / rel
            cur = dict(flatten(json.loads(p.read_text(encoding='utf-8-sig')))) if p.exists() else {}
            for ptr, v in old[rel].items():
                if ptr not in cur: out['removed'].append({'file': rel, 'pointer': ptr, 'was': v, 'review': status.get((rel, ptr))})
                elif cur[ptr] != v: out['changed'].append({'file': rel, 'pointer': ptr, 'was': v, 'now': cur[ptr], 'review': status.get((rel, ptr))})
            for ptr, v in cur.items():
                if ptr not in old[rel]: out['new'].append({'file': rel, 'pointer': ptr, 'now': v})
    print('data leaves: ' + ', '.join(f'{len(v)} {k}' for k, v in out.items()))
    for k, rows in out.items():
        by = collections.Counter(r['file'] for r in rows)
        if by: print(f'  {k}: ' + ', '.join(f'{f} {n}' for f, n in sorted(by.items())))
    sims = [r for r, _ in drift if r.startswith('sim/')]
    if sims:
        baseline = {}
        for rel in sims:
            lines = artifact_path(ctx, seen[rel][2], 'site-simulation-lines.jsonl')
            if lines and lines.exists() and lines not in baseline:
                baseline[lines] = [(r['siteFile'], r['line'], r['code']) for r in map(json.loads, open(lines, encoding='utf-8'))]
            print(f'sim (reported only, not re-reviewed): {rel}: ', end='')
            if lines and lines in baseline:
                rg = sim_diff(ctx, rel, baseline[lines])
                print(f'{len(rg)} changed blocks; ' + ', '.join(f'{s}-{e or s}' for s, e, _, _ in rg[:8]) + (' ...' if len(rg) > 8 else ''))
            else: print('baseline line list not found')
    if a.out:
        Path(a.out).write_text(json.dumps(out, indent=1) + '\n', encoding='utf-8'); print(f'full list: {a.out}')

def cmd_new(a, ctx):
    ids = a.lead or []
    if not ids or not all(LEAD_ID.fullmatch(i) for i in ids): raise SystemExit('give --lead L<number> at least once')
    date = a.date or datetime.date.today().isoformat()
    leads = [{'id': i, 'title': a.title or 'TODO', 'status': a.status, 'summary': a.summary or 'TODO', 'reopenWhen': a.reopen_when or 'TODO'} for i in ids]
    if a.status_note: [l.update(statusNote=a.status_note) for l in leads]
    rec = {'v': 1, 'kind': a.kind, 'date': date, 'build': a.build, 'leads': leads, 'binding': 'research'}
    if a.status == 'exhausted': [l.update(searched=['TODO']) for l in leads]
    body = {'date': date, 'title': a.title or 'TODO', 'record': rec}
    if a.note: body['note'] = a.note
    errs = validate_record(rec, date)
    if errs: raise SystemExit('; '.join(errs))
    out = Path(a.out) if a.out else ctx.prov_dirs[0] / f'frosty-{date}-{a.kind}-{"-".join(ids)}.json'
    if out.exists(): raise SystemExit(f'refusing existing output: {out}')
    out.write_text(jdump(body), encoding='utf-8', newline='\n'); print(out)

